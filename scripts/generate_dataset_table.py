#!/usr/bin/env python3
"""Generate a paper-facing instance table for AgentConflictBench."""

from __future__ import annotations

import argparse
import json
import textwrap
from pathlib import Path
from typing import Any
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parents[1]


def load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text())
    except FileNotFoundError:
        raise SystemExit(f"Missing JSON file: {path}") from None
    except json.JSONDecodeError as exc:
        raise SystemExit(f"Invalid JSON in {path}: {exc}") from None


def repo_slug(repo: str) -> str:
    parsed = urlparse(repo)
    path = parsed.path.strip("/")
    if path.endswith(".git"):
        path = path[:-4]
    return path or repo


def markdown_escape(value: object) -> str:
    text = " ".join(str(value).split())
    return text.replace("|", r"\|")


def short_text(value: object, width: int = 120) -> str:
    return textwrap.shorten(markdown_escape(value), width=width, placeholder="…")


def load_index(index_path: Path) -> list[dict[str, Any]]:
    data = load_json(index_path)
    instances = data.get("instances", [])
    if not isinstance(instances, list):
        raise SystemExit(f"Invalid index format: {index_path}")
    return [instance for instance in instances if isinstance(instance, dict)]


def load_metadata_by_id(root: Path, instances: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    metadata_by_id: dict[str, dict[str, Any]] = {}

    for instance in instances:
        instance_id = instance.get("id")
        path_value = instance.get("path")
        if not isinstance(instance_id, str) or not isinstance(path_value, str):
            continue

        metadata = load_json(root / path_value / "metadata.json")
        if not isinstance(metadata, dict):
            raise SystemExit(f"Invalid metadata object for {instance_id}")

        metadata_by_id[instance_id] = metadata

    return metadata_by_id


def markdown_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def render_table(instances: list[dict[str, Any]], metadata_by_id: dict[str, dict[str, Any]]) -> str:
    rows: list[list[str]] = []

    for instance in instances:
        instance_id = str(instance.get("id", ""))
        metadata = metadata_by_id.get(instance_id, {})
        rows.append(
            [
                f"`{markdown_escape(instance_id)}`",
                f"`{markdown_escape(repo_slug(str(instance.get('repo', ''))))}`",
                markdown_escape(instance.get("language", "")),
                f"`{markdown_escape(instance.get('conflict_type', ''))}`",
                markdown_escape(instance.get("status", "")),
                short_text(metadata.get("task_a", "")),
                short_text(metadata.get("task_b", "")),
                short_text(metadata.get("failure_summary", ""), width=150),
            ]
        )

    lines = [
        "# Paper Dataset Table",
        "",
        "<!-- Generated by scripts/generate_dataset_table.py. Do not edit by hand. -->",
        "",
        (
            "This table is the paper-facing snapshot of the reproduced "
            "AgentConflictBench seed dataset. The detailed benchmark artifacts "
            "remain inside `instances/`."
        ),
        "",
        *markdown_table(
            [
                "ID",
                "Repository",
                "Language",
                "Conflict Type",
                "Status",
                "Task A Intent",
                "Task B Intent",
                "Composition Failure",
            ],
            rows,
        ),
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--index",
        type=Path,
        default=ROOT / "instances" / "index.json",
        help="Path to instances/index.json.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Optional Markdown output path. If omitted, write to stdout.",
    )
    args = parser.parse_args()

    instances = load_index(args.index)
    metadata_by_id = load_metadata_by_id(ROOT, instances)
    table = render_table(instances, metadata_by_id)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(table)
    else:
        print(table, end="")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
