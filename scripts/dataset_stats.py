#!/usr/bin/env python3
"""Generate summary statistics for the AgentConflictBench dataset."""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parents[1]


def repo_slug(repo: str) -> str:
    parsed = urlparse(repo)
    path = parsed.path.strip("/")
    if path.endswith(".git"):
        path = path[:-4]
    return path or repo


def load_instances(index_path: Path) -> list[dict[str, object]]:
    data = json.loads(index_path.read_text())
    instances = data.get("instances", [])
    if not isinstance(instances, list):
        raise SystemExit(f"Invalid index format: {index_path}")
    return [instance for instance in instances if isinstance(instance, dict)]


def count_values(instances: list[dict[str, object]], field: str) -> Counter[str]:
    return Counter(str(instance.get(field, "")) for instance in instances)


def markdown_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def render_count_table(title: str, counts: Counter[str]) -> list[str]:
    rows = [[f"`{key}`", str(value)] for key, value in sorted(counts.items())]
    return [
        f"## {title}",
        "",
        *markdown_table(["Value", "Instances"], rows),
        "",
    ]


def render_summary(instances: list[dict[str, object]]) -> str:
    repo_slugs = [repo_slug(str(instance.get("repo", ""))) for instance in instances]
    language_counts = count_values(instances, "language")
    conflict_counts = count_values(instances, "conflict_type")
    source_counts = count_values(instances, "source")
    status_counts = count_values(instances, "status")

    rows = [
        ["Total instances", str(len(instances))],
        ["Upstream repositories", str(len(set(repo_slugs)))],
        ["Languages", str(len(language_counts))],
        ["Conflict categories", str(len(conflict_counts))],
        [
            "Researcher-constructed instances",
            str(source_counts.get("researcher_constructed", 0)),
        ],
        ["Reproduced instances", str(status_counts.get("reproduced", 0))],
    ]

    instance_rows = [
        [
            f"`{instance.get('id', '')}`",
            f"`{repo_slug(str(instance.get('repo', '')))}`",
            str(instance.get("language", "")),
            str(instance.get("conflict_type", "")),
            str(instance.get("source", "")),
            str(instance.get("status", "")),
        ]
        for instance in instances
    ]

    lines = [
        "# Dataset Summary",
        "",
        "<!-- Generated by scripts/dataset_stats.py. Do not edit counts by hand. -->",
        "",
        "## Current Status",
        "",
        *markdown_table(["Metric", "Value"], rows),
        "",
        "## Instances",
        "",
        *markdown_table(
            ["ID", "Repository", "Language", "Conflict Type", "Source", "Status"],
            instance_rows,
        ),
        "",
        *render_count_table("By Repository", Counter(repo_slugs)),
        *render_count_table("By Language", language_counts),
        *render_count_table("By Conflict Type", conflict_counts),
        "## Notes",
        "",
        "All current seed instances satisfy the AgentConflictBench acceptance rule:",
        "",
        "1. Patch A passes independently.",
        "2. Patch B passes independently.",
        "3. Patch A and Patch B apply cleanly to the same base commit.",
        "4. The composed patch pair fails a composition-level oracle.",
        "",
        "The next target is stronger JavaScript/TypeScript coverage, more "
        "test-assumption examples, and first dependency or performance/resource "
        "instances.",
        "",
    ]

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--index",
        type=Path,
        default=ROOT / "instances" / "index.json",
        help="Path to instances/index.json.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Optional Markdown output path. If omitted, write to stdout.",
    )
    args = parser.parse_args()

    instances = load_instances(args.index)
    summary = render_summary(instances)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(summary)
    else:
        print(summary, end="")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
